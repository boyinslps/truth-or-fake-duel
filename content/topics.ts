// 議題組題庫（30 個議題 × 3 則消息 = 90 張消息卡）。規格見企畫書第 6、11 節。
//
// 每個議題：3 筆查證資訊 ↔ 3 則消息，每筆資訊是其中一則消息的「關鍵證據」。
// 假消息改寫自事實查核網站（MyGoPen、台灣事實查核中心）查核過的真實謠言；
// 查證資訊取自查核報告中引述的專家與機關說法，或公認的基礎科學知識。
import type { Topic, TopicMessage, TrapType } from '../shared/types';

type F = [content: string, source: string];
type M = [statement: string, answer: boolean, difficulty: 1 | 2 | 3, trap: TrapType, key: number | number[], explanation: string];

function topic(id: string, title: string, category: string, facts: F[], messages: M[]): Topic {
  return {
    id,
    title,
    category,
    facts: facts.map(([content, source_name], i) => ({ id: `${id}_f${i + 1}`, content, source_name })),
    messages: messages.map(
      ([statement, answer, difficulty, trap_type, key, explanation], i): TopicMessage => ({
        id: `${id}_m${i + 1}`,
        statement,
        answer,
        difficulty,
        trap_type,
        key_facts: (Array.isArray(key) ? key : [key]).map((k) => `${id}_f${k}`),
        explanation,
      }),
    ),
  };
}

